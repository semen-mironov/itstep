g1 = int(input("Оцінка з 1-го предмета (1-12): "))
g2 = int(input("Оцінка з 2-го предмета (1-12): "))
g3 = int(input("Оцінка з 3-го предмета (1-12): "))
g4 = int(input("Оцінка з 4-го предмета (1-12): "))

if g1 >= 10 and g2 >= 10 and g3 >= 10 and g4 >= 10:
    print("Результат: Студент допускається до іспиту з відзнакою")

elif g1 < 8 or g2 < 8 or g3 < 8 or g4 < 8:
    print("Результат: Студент не допускається до іспиту")
else:
    print("Результат: Студент допускається до іспиту")